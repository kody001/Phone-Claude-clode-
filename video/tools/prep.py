"""Build timing data for the video from the forced alignment.

Outputs:
  data/words.js   - window.WORDS = [[text, vStart, vEnd, line, tag, voStart, voEnd], ...] (video time)
  data/timeline.json - inserts + total duration, shared with the audio mixer
  data/env.js     - VO loudness envelope at 60 fps (video time) for mouth flaps
"""
import json, re, subprocess, sys
import numpy as np
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCRIPT = ROOT.parent / "script.txt"
ALIGN = ROOT / "input" / "align.json"
VO = ROOT / "input" / "vo.mp3"
FPS = 60
PRE_ROLL = 0.6     # silence before first word
END_CARD = 7.0     # end card after the last word

# Pauses inserted into the narration (before the sentence that starts with `phrase`).
INSERTS = [
    ("So let's start in Egypt", 6.6, "title"),        # title card + chapter 1
    ("Now, remember Herodotus? When he got", 2.6, "ch2"),
    ("Meanwhile, back in Rod's own Greece", 2.6, "ch3"),
    ("Now, Greek medicine spread everywhere", 2.6, "ch4"),
]


def norm(s):
    return re.sub(r"[^a-z0-9]+", " ", s.lower()).strip()


def main():
    tagged = [l for l in SCRIPT.read_text().split("\n") if l.strip()]
    plain_lines = [re.sub(r"\[[^\]]*\] ?", "", l) for l in tagged]
    plain = "\n".join(plain_lines) + "\n"

    d = json.load(open(ALIGN))
    words = []

    def walk(n):
        if n.get("type") == "word":
            words.append(n)
        for c in n.get("timeline") or []:
            walk(c)

    for n in d:
        walk(n)

    # line index + tag for each char offset of plain text
    line_starts, off = [], 0
    for l in plain_lines:
        line_starts.append(off)
        off += len(l) + 1

    # tag spans per line: list of (plainOffsetInLine, tag)
    tag_spans = []
    for l in tagged:
        spans, pos, out = [], 0, ""
        for m in re.finditer(r"\[([^\]]*)\] ?", l):
            out += l[pos:m.start()]
            spans.append((len(out), m.group(1)))
            pos = m.end()
        tag_spans.append(spans)

    out = []
    prev_end = -1
    for w in words:
        s, e = w["startOffsetUtf16"], w["endOffsetUtf16"]
        if s < prev_end and out:   # piece of a hyphenated word already covered (e.g. "can-do")
            out[-1][2] = w["endTime"]
            continue
        # extend to include trailing punctuation / closing quotes
        while e < len(plain) and plain[e] not in " \n":
            e += 1
        # include leading quote
        while s > 0 and plain[s - 1] in "\"'“":
            s -= 1
        prev_end = e
        text = plain[s:e]
        li = max(i for i, ls in enumerate(line_starts) if ls <= w["startOffsetUtf16"])
        col = w["startOffsetUtf16"] - line_starts[li]
        tag = ""
        for (p, t) in tag_spans[li]:
            if p <= col:
                tag = t
        out.append([text, w["startTime"], w["endTime"], li, tag])

    # resolve inserts
    flat = [norm(t[0]) for t in out]
    inserts = []
    for phrase, dur, kind in INSERTS:
        target = norm(phrase)
        nw = len(phrase.split())
        idx = None
        for i in range(len(flat) - nw):
            if " ".join(flat[i:i + nw]) == target:
                idx = i
                break
        if idx is None:
            sys.exit(f"insert phrase not found: {phrase}")
        at = (out[idx - 1][2] + out[idx][1]) / 2
        inserts.append({"vo": round(at, 3), "dur": dur, "kind": kind, "word": idx})

    def v2t(v):
        return PRE_ROLL + v + sum(i["dur"] for i in inserts if i["vo"] <= v)

    for i in inserts:
        i["start"] = round(v2t(i["vo"]) - i["dur"], 3)

    vo_dur = float(subprocess.check_output([
        "ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(VO)]).decode())
    total = v2t(vo_dur) + END_CARD

    rows = []
    for t in out:
        rows.append([t[0], round(v2t(t[1]), 3), round(v2t(t[2]), 3), t[3], t[4], round(t[1], 3), round(t[2], 3)])

    (ROOT / "data").mkdir(exist_ok=True)
    (ROOT / "data" / "words.js").write_text(
        "// generated by tools/prep.py\nwindow.WORDS=" + json.dumps(rows, separators=(",", ":")) +
        ";\nwindow.INSERTS=" + json.dumps(inserts) + ";\nwindow.TOTAL=" + str(round(total, 3)) + ";\n")
    json.dump({"preRoll": PRE_ROLL, "inserts": inserts, "voDuration": vo_dur, "total": total, "fps": FPS},
              open(ROOT / "data" / "timeline.json", "w"), indent=1)

    # loudness envelope (video time) for lip sync
    raw = subprocess.check_output(["ffmpeg", "-v", "error", "-i", str(VO), "-ac", "1", "-ar", "16000",
                                   "-f", "s16le", "-"])
    a = np.frombuffer(raw, dtype=np.int16).astype(np.float32) / 32768
    hop = 16000 // FPS
    n = len(a) // hop
    rms = np.sqrt((a[:n * hop].reshape(n, hop) ** 2).mean(1) + 1e-9)
    db = 20 * np.log10(rms)
    lev = np.clip((db + 50) / 35, 0, 1)
    nf = int(total * FPS) + 1
    env = np.zeros(nf)
    for f in range(nf):
        tt = f / FPS
        # inverse map video time -> vo time
        v = tt - PRE_ROLL
        inside = False
        for i in inserts:
            if i["start"] <= tt < i["start"] + i["dur"]:
                inside = True
            if tt >= i["start"] + i["dur"]:
                v -= i["dur"]
        if inside or v < 0:
            continue
        k = int(v * FPS)
        if k < n:
            env[f] = lev[k]
    (ROOT / "data" / "env.js").write_text(
        "window.ENV=\"" + "".join(chr(48 + int(x * 40)) for x in env) + "\";\n")
    print(f"words={len(rows)} total={total:.2f}s inserts={[(i['kind'], i['start']) for i in inserts]}")


if __name__ == "__main__":
    main()
